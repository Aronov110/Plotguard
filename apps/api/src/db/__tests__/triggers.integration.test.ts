import { setTimeout as sleep } from "node:timers/promises";
import { eq } from "drizzle-orm";
import pg from "pg";
import { afterAll, beforeAll, beforeEach, describe, expect, it } from "vitest";
import { createDatabase, type DatabaseHandle } from "../client.ts";
import { documents } from "../schema/documents.ts";
import { projects } from "../schema/projects.ts";
import { users } from "../schema/users.ts";
import { databaseName } from "../test-support/assert-test-database.ts";
import { insertDocument, insertProject, insertUser } from "../test-support/factories.ts";
import {
  connectTestDatabase,
  createScratchDatabase,
  resetTables,
} from "../test-support/test-database.ts";

describe("updated_at trigger", () => {
  let handle: DatabaseHandle;

  beforeAll(() => {
    handle = connectTestDatabase();
  });
  afterAll(async () => {
    await handle.close();
  });
  beforeEach(async () => {
    await resetTables(handle);
  });

  it("starts equal to created_at on insert", async () => {
    const user = await insertUser(handle.db);

    expect(user.updatedAt.getTime()).toBe(user.createdAt.getTime());
  });

  it("advances updated_at on update and leaves created_at alone (users)", async () => {
    const user = await insertUser(handle.db);
    await sleep(25);

    await handle.db.update(users).set({ displayName: "New" }).where(eq(users.id, user.id));

    const [row] = await handle.db.select().from(users).where(eq(users.id, user.id));
    expect(row?.updatedAt.getTime()).toBeGreaterThan(user.updatedAt.getTime());
    expect(row?.createdAt.getTime()).toBe(user.createdAt.getTime());
  });

  it("advances updated_at on update and leaves created_at alone (projects)", async () => {
    const user = await insertUser(handle.db);
    const project = await insertProject(handle.db, user.id);
    await sleep(25);

    await handle.db.update(projects).set({ title: "Renamed" }).where(eq(projects.id, project.id));

    const [row] = await handle.db.select().from(projects).where(eq(projects.id, project.id));
    expect(row?.updatedAt.getTime()).toBeGreaterThan(project.updatedAt.getTime());
    expect(row?.createdAt.getTime()).toBe(project.createdAt.getTime());
  });

  it("advances updated_at on update and leaves created_at alone (documents)", async () => {
    const user = await insertUser(handle.db);
    const project = await insertProject(handle.db, user.id);
    const doc = await insertDocument(handle.db, project.id);
    await sleep(25);

    await handle.db
      .update(documents)
      .set({ content: "INT. ROOM - DAY", wordCount: 3 })
      .where(eq(documents.id, doc.id));

    const [row] = await handle.db.select().from(documents).where(eq(documents.id, doc.id));
    expect(row?.updatedAt.getTime()).toBeGreaterThan(doc.updatedAt.getTime());
    expect(row?.createdAt.getTime()).toBe(doc.createdAt.getTime());
  });

  it("ignores an attempt to write updated_at directly", async () => {
    const user = await insertUser(handle.db);
    const longAgo = new Date("2001-01-01T00:00:00.000Z");

    await handle.db.update(users).set({ updatedAt: longAgo }).where(eq(users.id, user.id));

    const [row] = await handle.db.select().from(users).where(eq(users.id, user.id));
    expect(row?.updatedAt.getTime()).toBeGreaterThan(longAgo.getTime());
  });

  it("also fires for raw SQL updates that bypass the ORM", async () => {
    const user = await insertUser(handle.db);
    await sleep(25);

    await handle.pool.query("update users set display_name = 'raw' where id = $1", [user.id]);

    const [row] = await handle.db.select().from(users).where(eq(users.id, user.id));
    expect(row?.updatedAt.getTime()).toBeGreaterThan(user.updatedAt.getTime());
  });

  it("does not touch rows that were not updated", async () => {
    const changed = await insertUser(handle.db);
    const untouched = await insertUser(handle.db);
    await sleep(25);

    await handle.db.update(users).set({ displayName: "x" }).where(eq(users.id, changed.id));

    const [row] = await handle.db.select().from(users).where(eq(users.id, untouched.id));
    expect(row?.updatedAt.getTime()).toBe(untouched.updatedAt.getTime());
  });
});

describe("timestamps and time zones", () => {
  let handle: DatabaseHandle;

  beforeAll(() => {
    handle = connectTestDatabase();
  });
  afterAll(async () => {
    await handle.close();
  });
  beforeEach(async () => {
    await resetTables(handle);
  });

  it("forces UTC on pooled sessions even when the database default is another zone", async () => {
    const scratch = await createScratchDatabase();
    const scratchName = databaseName(new URL(scratch.url));
    try {
      // The name is generated by createScratchDatabase and already passed the *_test guard.
      await handle.pool.query(`alter database "${scratchName}" set timezone = 'Asia/Tokyo'`);

      // Control: a plain client inherits the database default, so the setup really is non-UTC.
      const plain = new pg.Client({ connectionString: scratch.url });
      await plain.connect();
      try {
        const { rows } = await plain.query<{ zone: string }>(
          "select current_setting('TimeZone') as zone",
        );
        expect(rows[0]?.zone).toBe("Asia/Tokyo");
      } finally {
        await plain.end();
      }

      // The app's pool overrides it.
      const pooled = createDatabase(scratch.url);
      try {
        const { rows } = await pooled.pool.query<{ zone: string }>(
          "select current_setting('TimeZone') as zone",
        );
        expect(rows[0]?.zone).toBe("UTC");
      } finally {
        await pooled.close();
      }
    } finally {
      await scratch.drop();
    }
  });

  it("returns the same instant regardless of the session time zone", async () => {
    const user = await insertUser(handle.db);
    const client = await handle.pool.connect();
    try {
      const epochs: number[] = [];
      for (const zone of ["UTC", "Asia/Tokyo", "America/Los_Angeles", "Pacific/Kiritimati"]) {
        await client.query(`set time zone '${zone}'`);
        const { rows } = await client.query<{ epoch: string }>(
          "select extract(epoch from created_at)::text as epoch from users where id = $1",
          [user.id],
        );
        epochs.push(Number(rows[0]?.epoch));
      }

      // A missing row would give NaN, and a Set of NaNs has size 1, so check for real numbers.
      expect(epochs).toHaveLength(4);
      expect(epochs.every(Number.isFinite)).toBe(true);
      expect(new Set(epochs).size).toBe(1);
      expect(epochs[0]).toBeCloseTo(user.createdAt.getTime() / 1000, 2);
    } finally {
      client.release();
    }
  });

  it("round-trips a Date with millisecond precision", async () => {
    const user = await insertUser(handle.db);
    const project = await insertProject(handle.db, user.id, {
      updatedAt: new Date("2026-03-04T05:06:07.089Z"),
    });

    expect(project.updatedAt.toISOString()).toBe("2026-03-04T05:06:07.089Z");
  });
});
